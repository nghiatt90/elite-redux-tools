#!/usr/bin/env node
// One-off generator (not run as part of the build) for two files under
// src/engine/abilities/impl/:
//
//   00-flags.ts       -- abilities covered ENTIRELY by declarative bitfields (no
//                        hook at all) -- real AbilityImpl entries, nothing to port.
//   99-unmodelled.ts  -- every OTHER damage-relevant ability, as an explicit
//                        UnmodelledAbility stub. This is what makes the Task 9
//                        coverage gate pass immediately: every damage-relevant
//                        ability is accounted for from day one, either by a real
//                        port or by name here. As Task 10 batches port an ability,
//                        delete its line from this file and add a real entry to the
//                        relevant 0N-*.ts batch instead -- the gate keeps passing
//                        throughout, and this file's shrinking size *is* the
//                        ability-porting progress bar.
//
// Both are generated once and the *output* is committed as ordinary source; re-run
// this script only after abilityHooks.json changes (an upstream bump).
//
// Usage: node scripts/generate-declarative-abilities.mjs

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const DATA_DIR = new URL('../../data/v2.65beta/', import.meta.url)
const IMPL_DIR = new URL('../src/engine/abilities/impl/', import.meta.url)
const hooks = JSON.parse(readFileSync(fileURLToPath(new URL('abilityHooks.json', DATA_DIR)), 'utf-8'))

const FLAG_FIELDS = [
  'adaptability',
  'unaware',
  'breakable',
  'levitate',
  'omniStab',
  'skillLink',
  'fortKnox',
  'resistsFortKnox',
  'magicGuard',
  'noRecoil',
  'halfRecoil',
  'foesMinRoll',
  'megaLauncherBoost',
  'noDamageHits',
  'ruinStat',
  'negatesBurnAtkDrop',
  'negatesFrzSpatkDrop',
  'noBurnDamage',
]

// Mirrors pipeline/src/erdata/ability_hooks.py's _DAMAGE_HOOKS exactly -- the set of
// hook kinds that actually change a damage number. An ability can define OTHER
// (non-damage) hooks -- onEntry, onAbsorb's non-damage siblings, onStatusImmune,
// etc. -- and still need nothing but its declarative bitfields for THIS engine.
// The original predicate here checked "zero hooks of any kind", which wrongly
// routed every ability with an unrelated non-damage hook into 99-unmodelled.ts.
const DAMAGE_HOOKS = new Set([
  'onOffensiveMultiplier',
  'onDefensiveMultiplier',
  'onStat',
  'onStab',
  'onCrit',
  'onTypeEffectiveness',
  'onAfterTypeEffectiveness',
  'onChooseOffensiveStat',
  'onChooseDefensiveStat',
  'onSwapSplit',
  'onMoveType',
  'onRecoil',
  // Keep in sync with pipeline/src/erdata/ability_hooks.py's _DAMAGE_HOOKS --
  // these 6 were added after an audit found they change the damage number too.
  'onParentalBond',
  'onAbsorb',
  'onImmune',
  'onInfiltrate',
  'onModifyMoveFlags',
  'onMoldBreaker',
])

const declarative = []
const unmodelled = []

for (const ability of Object.values(hooks).sort((a, b) => a.id.localeCompare(b.id))) {
  if (!ability.damageRelevant) continue

  if (!Object.keys(ability.hooks).some((h) => DAMAGE_HOOKS.has(h))) {
    const flags = {}
    for (const field of FLAG_FIELDS) {
      const raw = ability.bitfields[field]
      if (raw === undefined) continue
      if (raw === 'TRUE') flags[field] = true
      else if (/^\d+$/.test(raw)) flags[field] = Number(raw)
      else throw new Error(`${ability.id}.${field}: unexpected raw value ${raw}`)
    }
    declarative.push({ id: ability.id, line: ability.sourceLine, flags, addsType: ability.bitfields.addsType })
  } else {
    unmodelled.push({ id: ability.id, line: ability.sourceLine, reasons: ability.damageRelevantReasons })
  }
}

function writeFlagsFile() {
  const lines = []
  lines.push('// GENERATED by scripts/generate-declarative-abilities.mjs -- do not hand-edit.')
  lines.push('// Regenerate with: node scripts/generate-declarative-abilities.mjs')
  lines.push('//')
  lines.push('// Every ability abilityHooks.json flags damageRelevant that is covered ENTIRELY by')
  lines.push('// declarative bitfields -- no onOffensiveMultiplier/onStat/etc. hook at all -- so')
  lines.push('// there is nothing to hand-port; the flags themselves ARE the implementation.')
  lines.push('')
  lines.push("import type { AbilityImpl } from '../types'")
  lines.push('')
  lines.push('export const DECLARATIVE_ABILITIES: AbilityImpl[] = [')
  for (const e of declarative) {
    const parts = [`{ id: '${e.id}', src: 'src/abilities.cc:${e.line}'`]
    if (Object.keys(e.flags).length > 0) {
      parts.push(`flags: { ${Object.entries(e.flags)
        .map(([k, v]) => `${k}: ${v}`)
        .join(', ')} }`)
    }
    if (e.addsType) parts.push(`addsType: '${e.addsType.replace('TYPE_', '')}'`)
    lines.push(`  ${parts.join(', ')} },`)
  }
  lines.push(']')
  lines.push('')
  writeFileSync(fileURLToPath(new URL('00-flags.ts', IMPL_DIR)), lines.join('\n'))
}

function writeUnmodelledFile() {
  const lines = []
  lines.push('// GENERATED by scripts/generate-declarative-abilities.mjs -- hand-edit freely by')
  lines.push('// DELETING an entry once you port it to a real batch file (01-*.ts, 02-*.ts, ...);')
  lines.push('// do not regenerate this file wholesale once porting has started, or it will')
  lines.push('// re-add abilities that were already ported. Regenerate only right after an')
  lines.push('// abilityHooks.json update, then re-remove the ones already ported elsewhere.')
  lines.push('//')
  lines.push('// Every damage-relevant ability with a real lambda/alias/macro hook -- i.e.')
  lines.push('// everything Task 10 still needs to port -- starts here as an explicit')
  lines.push('// UNMODELLED stub, so the coverage gate (abilities/coverage.test.ts) passes from')
  lines.push('// day one instead of only once every single ability is done. This file shrinking')
  lines.push('// to zero entries IS the ability-porting progress bar.')
  lines.push('')
  lines.push("import type { AbilityEntry } from '../types'")
  lines.push('')
  lines.push('export const UNMODELLED_ABILITIES: AbilityEntry[] = [')
  for (const e of unmodelled) {
    lines.push(
      `  { id: '${e.id}', src: 'src/abilities.cc:${e.line}', unmodelled: 'not yet ported (hooks: ${e.reasons.join(', ')})' },`,
    )
  }
  lines.push(']')
  lines.push('')
  writeFileSync(fileURLToPath(new URL('99-unmodelled.ts', IMPL_DIR)), lines.join('\n'))
}

writeFlagsFile()
writeUnmodelledFile()
console.log(`declarative: ${declarative.length}, unmodelled stubs: ${unmodelled.length}`)
