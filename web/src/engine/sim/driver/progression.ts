export type GymNumber = 1 | 2 | 3 | 4 | 5 | 6 | 7 | 8

export interface StageKey {
  highestBadge: number
  badgeCount: number
  braceletHeld: boolean
}

export interface ProgressionRow {
  fightId: string            // first trainer id of the fight in script order
  requiredBefore: GymNumber[] // gyms that must already be cleared when the fight can occur
  mayBefore: GymNumber[]      // skippable gyms that may or may not be cleared
  evidence: string
  inferred?: boolean
}

/**
 * Returns the gyms cleared before this fight given a candidate gym subset:
 * requiredBefore ∪ (mayBefore ∩ subset).
 */
export function clearedBefore(
  row: ProgressionRow,
  subset: ReadonlySet<GymNumber>,
): Set<GymNumber> {
  const cleared = new Set<GymNumber>(row.requiredBefore)
  for (const gym of row.mayBefore) {
    if (subset.has(gym)) {
      cleared.add(gym)
    }
  }
  return cleared
}

/**
 * Derives the StageKey from clearedBefore.
 *
 * Rule source: solver-v2-plan.md:50-54.
 * - getHighestBadge returns the highest FLAG_BADGE0x_GET flag held (src/pokemon.c:4635-4647),
 *   not a badge count (0 if empty).
 * - The Mega Bracelet is handed over in Norman's Gym 5 script
 *   (data/maps/PetalburgCity_Gym/scripts.pory:1755-1761), so braceletHeld requires gym 5 cleared.
 */
export function stageKeyFor(
  row: ProgressionRow,
  subset: ReadonlySet<GymNumber>,
): StageKey {
  const cleared = clearedBefore(row, subset)
  let highestBadge = 0
  for (const gym of cleared) {
    if (gym > highestBadge) {
      highestBadge = gym
    }
  }
  return {
    highestBadge,
    badgeCount: cleared.size,
    braceletHeld: cleared.has(5),
  }
}

/**
 * Highest badge min/max bounds for innate gating and level caps (innate-gating-plan decision 2).
 * min = largest of requiredBefore (0 if empty)
 * max = largest of requiredBefore ∪ mayBefore (0 if empty)
 */
export function highestBadgeRange(row: ProgressionRow): { min: number; max: number } {
  let min = 0
  for (const gym of row.requiredBefore) {
    if (gym > min) {
      min = gym
    }
  }
  let max = min
  for (const gym of row.mayBefore) {
    if (gym > max) {
      max = gym
    }
  }
  return { min, max }
}

/**
 * Stable string representation for de-duplicating StageKeys, e.g. "h3-n3-b0".
 */
export function stageKeyId(key: StageKey): string {
  return `h${key.highestBadge}-n${key.badgeCount}-b${key.braceletHeld ? 1 : 0}`
}

/**
 * Enumerates every subset of gyms 1-8 (256 total) containing all requiredBefore gyms
 * for rows in mandatoryFightIds, ordered by subset size ascending, then lexicographically.
 */
export function legalSubsets(
  rows: readonly ProgressionRow[],
  mandatoryFightIds: ReadonlySet<string>,
): Set<GymNumber>[] {
  const mandatoryGyms = new Set<GymNumber>()
  for (const row of rows) {
    if (mandatoryFightIds.has(row.fightId)) {
      for (const gym of row.requiredBefore) {
        mandatoryGyms.add(gym)
      }
    }
  }

  const gyms: readonly GymNumber[] = [1, 2, 3, 4, 5, 6, 7, 8]
  const result: Set<GymNumber>[] = []

  // Combinations generated by size ascending (0 to 8), and lexicographically within each size.
  for (let size = 0; size <= gyms.length; size++) {
    const collectCombos = (start: number, current: GymNumber[]) => {
      if (current.length === size) {
        let hasAllMandatory = true
        for (const mg of mandatoryGyms) {
          if (!current.includes(mg)) {
            hasAllMandatory = false
            break
          }
        }
        if (hasAllMandatory) {
          result.push(new Set<GymNumber>(current))
        }
        return
      }
      for (let i = start; i < gyms.length; i++) {
        current.push(gyms[i])
        collectCombos(i + 1, current)
        current.pop()
      }
    }
    collectCombos(0, [])
  }

  return result
}

/**
 * De-duplicated StageKeys across all rows and all given subsets, sorted by stageKeyId.
 */
export function distinctStageKeys(
  rows: readonly ProgressionRow[],
  subsets: readonly ReadonlySet<GymNumber>[],
): StageKey[] {
  const map = new Map<string, StageKey>()
  for (const row of rows) {
    for (const subset of subsets) {
      const key = stageKeyFor(row, subset)
      const id = stageKeyId(key)
      if (!map.has(id)) {
        map.set(id, key)
      }
    }
  }
  return Array.from(map.values()).sort((a, b) => stageKeyId(a).localeCompare(stageKeyId(b)))
}
